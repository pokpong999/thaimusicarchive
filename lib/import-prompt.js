export function systemPrompt(mode) {
  const head = 'คุณคือผู้ถอดโน้ตดนตรีจากภาพให้หอจดหมายเหตุดนตรีไทย ตอบเป็นข้อความโน้ตล้วน ๆ ตามไวยากรณ์ที่กำหนด ห้ามมีคำอธิบายอื่น ห้ามใช้ markdown/code block';
  if (mode === 'thai') return `${head}\n\n${GRAMMAR_THAI}\n\nบรรทัดแรกของคำตอบต้องเป็น "% format=thai"`;
  if (mode === 'western') return `${head}\n\n${GRAMMAR_WESTERN}\n\nบรรทัดแรกของคำตอบต้องเป็น "% format=western"`;
  return `${head}\n\nก่อนอื่นดูว่าภาพเป็นโน้ตแบบไหน: (ก) โน้ตไทย (ตารางอักษรไทย ดรมฟซลท หรือฟอนต์ TH Notation) หรือ (ข) โน้ตสากลบรรทัด 5 เส้น\nบรรทัดแรกของคำตอบต้องเป็น "% format=thai" หรือ "% format=western" แล้วตามด้วยโน้ตตามไวยากรณ์ของแบบนั้น\n\n${GRAMMAR_THAI}\n\n${GRAMMAR_WESTERN}`;
}

// อ่านผลลัพธ์: แยก format จากบรรทัด % · ตัด code fence ที่เผลอใส่
export function parseModelText(raw) {
  let text = String(raw || '').replace(/```[a-z]*\n?/g, '').trim();
  let format = null;
  const m = text.match(/^%\s*format\s*=\s*(thai|western)/im);
  if (m) format = m[1].toLowerCase();
  const notes = text.split('\n').filter(l => /^%\s*(หมายเหตุ|ไม่แน่ใจ|note|meta)/i.test(l.trim()));
  return { text, format, notes };
}

